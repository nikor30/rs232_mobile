static void rc2Key(const uint8_t *key, size_t t, unsigned effBits, uint16_t *k) {
  uint8_t bkey[128];
  if (effBits < 8) effBits = 8;
  if (effBits > 1024) effBits = 1024;
  memcpy(bkey, key, t);
  uint8_t t8 = (uint8_t)((effBits + 7) / 8);
  uint8_t tm = (uint8_t)((1 << (8 - (t8 * 8 - (int)effBits))) - 1);
  for (int i = (int)t; i < 128; i++) bkey[i] = permute[(bkey[i - 1] + bkey[i - (int)t]) & 255];
  bkey[128 - t8] = permute[bkey[128 - t8] & tm];
  for (int i = 127 - t8; i >= 0; i--) bkey[i] = permute[bkey[i + 1] ^ bkey[i + t8]];
  for (int i = 0; i < 64; i++) k[i] = bkey[2 * i] + 256U * bkey[2 * i + 1];
}

static inline uint16_t ror16(uint16_t x, int p) { return (uint16_t)((x >> p) | (x << (16 - p))); }

static void rc2Decrypt(const uint16_t *k, const uint8_t *in, uint8_t *out) {
  uint16_t r[4];
  for (int i = 0; i < 4; i++) r[i] = in[2 * i] + 256U * in[2 * i + 1];
  int j = 63;
  auto invMix = [&]() {
    r[3] = ror16(r[3], 5); r[3] -= k[j--] + (r[2] & r[1]) + (~r[2] & r[0]);
    r[2] = ror16(r[2], 3); r[2] -= k[j--] + (r[1] & r[0]) + (~r[1] & r[3]);
    r[1] = ror16(r[1], 2); r[1] -= k[j--] + (r[0] & r[3]) + (~r[0] & r[2]);
    r[0] = ror16(r[0], 1); r[0] -= k[j--] + (r[3] & r[2]) + (~r[3] & r[1]);
  };
  auto invMash = [&]() {
    r[3] -= k[r[2] & 63]; r[2] -= k[r[1] & 63]; r[1] -= k[r[0] & 63]; r[0] -= k[r[3] & 63];
  };
  for (int i = 0; i < 5; i++) invMix();
  invMash();
  for (int i = 0; i < 6; i++) invMix();
  invMash();
  for (int i = 0; i < 5; i++) invMix();
  for (int i = 0; i < 4; i++) { out[2 * i] = r[i] & 255; out[2 * i + 1] = (uint8_t)(r[i] >> 8); }
}

// ------------------------------------------------------------------ CBC
bool cbcDecrypt(Cipher c, const uint8_t *key, size_t keyLen, const uint8_t iv[8], const uint8_t *in, size_t len, uint8_t *out,
                unsigned rc2Bits) {
  if (len == 0 || len % 8) return false;
  uint32_t ks[3][32];
  uint16_t rk[64];
  if (c == DES_CBC) {
    if (keyLen != 8) return false;
    deskey(key, true, ks[0]);
  } else if (c == DES_EDE3_CBC) {
    if (keyLen != 24 && keyLen != 16) return false;
    const uint8_t *k3 = keyLen == 24 ? key + 16 : key;     // two-key 3DES: K3 = K1
    deskey(k3, true, ks[0]);
    deskey(key + 8, false, ks[1]);
    deskey(key, true, ks[2]);
  } else {
    if (keyLen < 1 || keyLen > 128) return false;
    rc2Key(key, keyLen, rc2Bits ? rc2Bits : keyLen * 8, rk);
  }
  uint8_t prev[8], cur[8];
  memcpy(prev, iv, 8);
  for (size_t off = 0; off < len; off += 8) {
    memcpy(cur, in + off, 8);
    uint8_t blk[8];
    if (c == RC2_CBC) {
      rc2Decrypt(rk, cur, blk);
    } else {
      uint32_t w[2] = {load32(cur), load32(cur + 4)};
      desfunc(w, ks[0]);
      if (c == DES_EDE3_CBC) {
        desfunc(w, ks[1]);
        desfunc(w, ks[2]);
      }
      store32(w[0], blk);
      store32(w[1], blk + 4);
    }
    for (int i = 0; i < 8; i++) out[off + i] = blk[i] ^ prev[i];
    memcpy(prev, cur, 8);
  }
  memset(ks, 0, sizeof(ks));
  memset(rk, 0, sizeof(rk));
  return true;
}

