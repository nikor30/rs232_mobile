static inline uint32_t rol(uint32_t x, int n) { return (x << n) | (x >> (32 - n)); }
static inline uint32_t ror(uint32_t x, int n) { return (x >> n) | (x << (32 - n)); }

static void cookey(const uint32_t *raw1, uint32_t *keyout) {
  uint32_t *cook = keyout;
  for (int i = 0; i < 16; i++, raw1++) {
    const uint32_t *raw0 = raw1++;
    *cook = (*raw0 & 0x00fc0000UL) << 6;
    *cook |= (*raw0 & 0x00000fc0UL) << 10;
    *cook |= (*raw1 & 0x00fc0000UL) >> 10;
    *cook++ |= (*raw1 & 0x00000fc0UL) >> 6;
    *cook = (*raw0 & 0x0003f000UL) << 12;
    *cook |= (*raw0 & 0x0000003fUL) << 16;
    *cook |= (*raw1 & 0x0003f000UL) >> 4;
    *cook++ |= (*raw1 & 0x0000003fUL);
  }
}

// decrypt = true: round keys in reverse order
static void deskey(const uint8_t *key, bool decrypt, uint32_t *keyout) {
  uint32_t kn[32];
  uint8_t pc1m[56], pcr[56];
  for (int j = 0; j < 56; j++) {
    uint32_t l = pc1[j], m = l & 7;
    pc1m[j] = (key[l >> 3] & bytebit[m]) == bytebit[m] ? 1 : 0;
  }
  for (int i = 0; i < 16; i++) {
    uint32_t m = decrypt ? (15 - i) << 1 : i << 1, n = m + 1;
    kn[m] = kn[n] = 0;
    int j;
    for (j = 0; j < 28; j++) {
      uint32_t l = j + totrot[i];
      pcr[j] = l < 28 ? pc1m[l] : pc1m[l - 28];
    }
    for (; j < 56; j++) {
      uint32_t l = j + totrot[i];
      pcr[j] = l < 56 ? pc1m[l] : pc1m[l - 28];
    }
    for (j = 0; j < 24; j++) {
      if (pcr[pc2[j]]) kn[m] |= bigbyte[j];
      if (pcr[pc2[j + 24]]) kn[n] |= bigbyte[j];
    }
  }
  cookey(kn, keyout);
}

static void desfunc(uint32_t *block, const uint32_t *keys) {
  uint32_t work, right = block[1], leftt = block[0];
  work = ((leftt >> 4) ^ right) & 0x0f0f0f0fUL; right ^= work; leftt ^= (work << 4);
  work = ((leftt >> 16) ^ right) & 0x0000ffffUL; right ^= work; leftt ^= (work << 16);
  work = ((right >> 2) ^ leftt) & 0x33333333UL; leftt ^= work; right ^= (work << 2);
  work = ((right >> 8) ^ leftt) & 0x00ff00ffUL; leftt ^= work; right ^= (work << 8);
  right = rol(right, 1);
  work = (leftt ^ right) & 0xaaaaaaaaUL; leftt ^= work; right ^= work;
  leftt = rol(leftt, 1);
  for (int round = 0; round < 8; round++) {
    work = ror(right, 4) ^ *keys++;
    leftt ^= SP7[work & 0x3f] ^ SP5[(work >> 8) & 0x3f] ^ SP3[(work >> 16) & 0x3f] ^ SP1[(work >> 24) & 0x3f];
    work = right ^ *keys++;
    leftt ^= SP8[work & 0x3f] ^ SP6[(work >> 8) & 0x3f] ^ SP4[(work >> 16) & 0x3f] ^ SP2[(work >> 24) & 0x3f];
    work = ror(leftt, 4) ^ *keys++;
    right ^= SP7[work & 0x3f] ^ SP5[(work >> 8) & 0x3f] ^ SP3[(work >> 16) & 0x3f] ^ SP1[(work >> 24) & 0x3f];
    work = leftt ^ *keys++;
    right ^= SP8[work & 0x3f] ^ SP6[(work >> 8) & 0x3f] ^ SP4[(work >> 16) & 0x3f] ^ SP2[(work >> 24) & 0x3f];
  }
  right = ror(right, 1);
  work = (leftt ^ right) & 0xaaaaaaaaUL; leftt ^= work; right ^= work;
  leftt = ror(leftt, 1);
  work = ((leftt >> 8) ^ right) & 0x00ff00ffUL; right ^= work; leftt ^= (work << 8);
  work = ((leftt >> 2) ^ right) & 0x33333333UL; right ^= work; leftt ^= (work << 2);
  work = ((right >> 16) ^ leftt) & 0x0000ffffUL; leftt ^= work; right ^= (work << 16);
  work = ((right >> 4) ^ leftt) & 0x0f0f0f0fUL; leftt ^= work; right ^= (work << 4);
  block[0] = right;
  block[1] = leftt;
}

static inline uint32_t load32(const uint8_t *p) { return ((uint32_t)p[0] << 24) | ((uint32_t)p[1] << 16) | ((uint32_t)p[2] << 8) | p[3]; }
static inline void store32(uint32_t v, uint8_t *p) { p[0] = v >> 24; p[1] = v >> 16; p[2] = v >> 8; p[3] = v; }

