#!/usr/bin/env python3
"""Enclosure for the carrier board + Waveshare ESP32-S3-Touch-LCD-2, revision 0.3.

    python3 generate_enclosure.py   # writes rs232_console_case.scad, body.stl, base.stl, previews

Design language (Rams / Ive): one quiet volume with continuous radii, symmetric faces, nothing
on the outside that is not used every day, no visible fasteners, seams only where you cannot see
them.  Two printed parts:

  * body - the whole shell: top with the display glass as its surface, all four walls down to the
           floor edge.  Ports, USB-C, antenna and the two service pin holes are the only openings.
  * base - a flat panel that sits INSIDE the walls at the bottom (seam only visible from below),
           held by six cantilever hooks that catch in a groove inside the walls.  It carries the
           carrier board on posts and the battery.  Pull the base to swap the battery; no tools,
           no screws.

Coordinates: carrier PCB top-left corner = origin, X right, Y towards the RJ45 edge, Z up with
Z = 0 on the carrier's top surface.  Module numbers come from carrier/generate.py (VERIFY).
Snap-fit rules (Hubs / Formlabs / Core77 FDM guides): hook length about 4-5 x thickness, 30 deg
lead-in, 45 deg return (releasable), 0.3 mm play, fillet at the root, PETG or ABS.
"""
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "carrier"))
import generate as G   # noqa: E402

V = G.V
usb_c = ((V["WS_USBC"][0] + V["WS_USBC"][1]) / 2, V["WS_USBC"][2])
P = {
    "pcb_w": G.BOARD_W, "pcb_h": G.BOARD_H, "pcb_t": 1.6,
    "gap": 0.5, "wall": 2.0, "end_wall": 3.6, "corner_r": 5.0, "edge_r": 1.2, "clr": 0.3,
    "base_t": 2.0, "base_inset": 0.6, "bat_t": 7.0, "pin_clr": 2.0,
    "z_top": V["WS_STACK"] + V["WS_PCB_T"] + V["WS_DISP_T"],    # glass top = body top
    "plate_t": 2.0,
    "ws_x0": G.WS_X0, "ws_y0": G.WS_Y0, "ws_w": V["WS_W"], "ws_l": V["WS_L"],
    "glass_w": V["WS_GLASS"][0], "glass_l": V["WS_GLASS"][1],
    "z_glass_bot": V["WS_STACK"] + V["WS_PCB_T"],
    "ch_pitch": G.CH_PITCH, "ch_x0": G.CH_CENTERS[0],
    "rj_w": V["RJ45_W"] + 0.6, "rj_h": V["RJ45_H"] + 0.6,
    "usb_x": G.ws_to_carrier(*usb_c)[0], "usb_z": V["WS_STACK"] - 1.6,
    "btn_x1": G.ws_to_carrier(sum(V["WS_BTN_X"][0]) / 2, 0)[0], "btn_x2": G.ws_to_carrier(sum(V["WS_BTN_X"][1]) / 2, 0)[0],
    "btn_z": V["WS_STACK"] - 1.6,
    "sma_y": 12.0, "sma_z": 7.5, "sma_d": 6.5,     # RP-SMA on the right side wall, near the top end
    "hook_w": 10.0, "hook_t": 1.6, "hook_len": 6.0, "hook_catch": 0.8,
    "hook_ys": [30.0, 80.0],          # long sides
    "hook_x_front": G.BOARD_W / 2,    # front and back wall
    "foot_d": 8.0, "foot_depth": 0.6,
}
HOLES_M25 = G.MOUNT_HOLES
HOLES_M2 = [tuple(round(v, 2) for v in h) for h in G.ws_holes_landscape()]

SCAD = r"""
// RS232 console server - enclosure 0.3 (body + base, snap fit, no screws)
// GENERATED by hardware/enclosure/generate_enclosure.py - edit the parameters there.
// part = 0: assembly, 1: body, 2: base, 3: exploded, 4: body from below
part = 0;
$fn = 64;

__PARAMS__

cav_x1 = -gap;  cav_x2 = pcb_w + gap;
cav_y1 = -1.0;  cav_y2 = pcb_h + gap;          // 1.0 at the USB-C end: the module's USB-C shell sticks out 1.9 mm
out_x1 = cav_x1 - wall; out_x2 = cav_x2 + wall;
out_y1 = cav_y1 - end_wall; out_y2 = cav_y2 + wall;
z_pcb_bot = -pcb_t;
z_bay_top = z_pcb_bot - pin_clr;
z_base_top = z_bay_top - bat_t;
z_base_bot = z_base_top - base_t;
z_bot = z_base_bot - base_inset;                // bottom edge of the body
z_plate_bot = z_top - plate_t;
groove_z = z_base_top + hook_len;               // where the hook catches engage
cx = (ws_x0 + ws_x0 + ws_w) / 2;

module rbox(x1, y1, x2, y2, z1, z2, r) {
    hull() for (x = [x1 + r, x2 - r], y = [y1 + r, y2 - r]) translate([x, y, z1]) cylinder(r = r, h = z2 - z1);
}
module box(x1, y1, x2, y2, z1, z2) { translate([x1, y1, z1]) cube([x2 - x1, y2 - y1, z2 - z1]); }
module stadium(x, y, w, h, z1, z2) { hull() for (dx = [-(w - h) / 2, (w - h) / 2]) translate([x + dx, y, z1]) cylinder(d = h, h = z2 - z1); }

// the outer volume: rounded corners (corner_r) and rounded edges (edge_r) everywhere
module volume(x1, y1, x2, y2, z1, z2) {
    minkowski() {
        rbox(x1 + edge_r, y1 + edge_r, x2 - edge_r, y2 - edge_r, z1 + edge_r, z2 - edge_r, corner_r - edge_r);
        sphere(r = edge_r, $fn = 24);
    }
}

// ------------------------------------------------------------------ openings
module openings() {
    // four RJ45 windows in the front wall, jacks sit behind the wall
    for (i = [0:3]) box(ch_x0 + i * ch_pitch - rj_w / 2, cav_y2 - 1, ch_x0 + i * ch_pitch + rj_w / 2, out_y2 + 2, -0.5, rj_h);
    // USB-C: stadium well through the end wall, centred on the device
    translate([0, out_y1 - 1, 0]) rotate([-90, 0, 0]) stadium(usb_x, -usb_z, 13.0, 7.5, 0, end_wall + 2);
    // BOOT / RST service pin holes, 1.5 mm, symmetric about the USB-C
    for (x = [btn_x1, btn_x2]) translate([x, out_y1 - 1, btn_z]) rotate([-90, 0, 0]) cylinder(d = 1.5, h = end_wall + 2);
    // RP-SMA bulkhead in the right side wall, out of the main view
    translate([cav_x2 - 1, sma_y, sma_z]) rotate([0, 90, 0]) cylinder(d = sma_d, h = wall + 2);
}

// ------------------------------------------------------------------ body
module body() {
    gx1 = cx - glass_w / 2 - 0.15; gx2 = cx + glass_w / 2 + 0.15;
    gy2 = ws_y0 + ws_l / 2 + glass_l / 2 + 0.15;
    difference() {
        volume(out_x1, out_y1, out_x2, out_y2, z_bot, z_top);
        // cavity, open at the bottom
        box(cav_x1, cav_y1, cav_x2, cav_y2, z_bot - 1, z_plate_bot);
        // the display glass is the top surface; the frame is open at the USB-C end
        box(gx1, out_y1 - 1, gx2, gy2, z_plate_bot - 1, z_top + 1);
        box(gx1, out_y1 - 1, gx2, cav_y1 + 1, z_glass_bot - 0.3, z_top + 1);     // end wall under the glass overhang
        openings();
        // groove inside the walls for the base hooks
        difference() {
            box(cav_x1 - hook_catch - clr, cav_y1 - hook_catch - clr, cav_x2 + hook_catch + clr, cav_y2 + hook_catch + clr, groove_z - 0.2, groove_z + 2.732 * hook_catch + 2 * clr);
            box(cav_x1 - 0.01, cav_y1 - 0.01, cav_x2 + 0.01, cav_y2 + 0.01, groove_z - 1, groove_z + 5);
        }
        // two pry notches in the bottom edge (only visible from below)
        for (x = [cav_x1 - wall - 1, cav_x2 - 0.5]) box(x, pcb_h / 2 - 4, x + wall + 1.5, pcb_h / 2 + 4, z_bot - 1, z_base_bot + 0.4);
        // port numbers, debossed into the top surface above the jacks
        for (i = [0:3]) translate([ch_x0 + i * ch_pitch, cav_y2 - 5.5, z_top - 0.4]) linear_extrude(1) text(str(i + 1), size = 4.5, halign = "center", valign = "center", font = "Liberation Sans:style=Regular");
    }
    // posts that press the carrier down onto the base pins
    for (h = holes_m25) difference() {
        translate([h[0], h[1], 0.3]) cylinder(d = 6.0, h = z_plate_bot - 0.3 + 0.1);
        translate([h[0], h[1], -1]) cylinder(d = 2.4 + 2 * clr, h = 5);
    }
}

// ------------------------------------------------------------------ base
module hook_at(x, y, ang) {        // cantilever growing up from the base, catch pointing outwards (+x after rotation)
    L = hook_len; t = hook_t; c = hook_catch;
    translate([x, y, z_base_top - 0.01]) rotate([0, 0, ang]) {
        translate([-t, -hook_w / 2, 0]) cube([t, hook_w, L]);
        translate([0, hook_w / 2, L]) rotate([90, 0, 0]) linear_extrude(hook_w) polygon([[-0.01, 0], [c, 1.732 * c], [-0.01, 2.732 * c]]);
        // root fillet
        translate([-t - 0.8, -hook_w / 2, 0]) difference() { cube([0.8, hook_w, 0.8]); translate([0, -1, 0.8]) rotate([-90, 0, 0]) cylinder(r = 0.8, h = hook_w + 2); }
    }
}
module base() {
    bx1 = cav_x1 + clr; bx2 = cav_x2 - clr; by1 = cav_y1 + clr; by2 = cav_y2 - clr;
    difference() {
        union() {
            rbox(bx1, by1, bx2, by2, z_base_bot, z_base_top, corner_r - wall);
            // carrier posts: shoulder + pin
            for (h = holes_m25) translate([h[0], h[1], z_base_top - 0.01]) { cylinder(d = 5.5, h = z_pcb_bot - z_base_top); cylinder(d = 2.4, h = z_pcb_bot - z_base_top + pcb_t + 2.0); }
            for (h = holes_m2)  translate([h[0], h[1], z_base_top - 0.01]) { cylinder(d = 5.0, h = z_pcb_bot - z_base_top); cylinder(d = 1.9, h = z_pcb_bot - z_base_top + pcb_t + 1.0); }
            // battery cradle: a low rim that keeps a 60 x 70 mm cell in place
            difference() {
                box(cx - 31, 18, cx + 31, 90, z_base_top, z_base_top + 1.5);
                box(cx - 30, 19, cx + 30, 89, z_base_top - 1, z_base_top + 3);
            }
            // hooks: two per long side, one per end
            for (y = hook_ys) { hook_at(bx1, y, 180); hook_at(bx2, y, 0); }
            hook_at(hook_x_front, by2, 90);
            hook_at(hook_x_front, by1, -90);
        }
        // feet recesses for 8 mm rubber feet
        for (x = [bx1 + 8, bx2 - 8], y = [by1 + 8, by2 - 8]) translate([x, y, z_base_bot - 0.01]) cylinder(d = foot_d, h = foot_depth);
        // mark, debossed into the underside
        translate([cx, pcb_h / 2, z_base_bot - 0.01]) mirror([1, 0, 0]) linear_extrude(0.4) text("RS232 CONSOLE", size = 4, halign = "center", valign = "center", font = "Liberation Sans:style=Regular");
    }
}

module carrier_preview() {
    color("#2d6a4f") box(0, 0, pcb_w, pcb_h, z_pcb_bot, 0);
    for (i = [0:3]) color("#c0c0c0") box(ch_x0 + i * ch_pitch - 7.95, pcb_h - 21.9, ch_x0 + i * ch_pitch + 7.95, pcb_h - 0.6, 0, 13.5);
    color("#1f3b73") box(ws_x0, ws_y0, ws_x0 + ws_w, ws_y0 + ws_l, z_glass_bot - 1.6, z_glass_bot);
    color("#0b0c10") box(cx - glass_w / 2, ws_y0 + ws_l / 2 - glass_l / 2, cx + glass_w / 2, ws_y0 + ws_l / 2 + glass_l / 2, z_glass_bot, z_top);
    color("#444") box(cx - 25, 20, cx + 25, 85, z_base_top, z_base_top + 6);
}

if (part == 1) body();
else if (part == 2) base();
else if (part == 3) { color("#e9e7e2") body(); translate([0, 0, -30]) color("#9a9a96") base(); translate([0, 0, -30]) carrier_preview(); }
else if (part == 4) color("#e9e7e2") body();
else { color("#e9e7e2") body(); color("#9a9a96") base(); carrier_preview(); }
"""


def main():
    params = [f"{k} = {v};" for k, v in P.items()]
    params.append("holes_m25 = " + str([list(h) for h in HOLES_M25]) + ";")
    params.append("holes_m2 = " + str([list(h) for h in HOLES_M2]) + ";")
    scad = SCAD.replace("__PARAMS__", "\n".join(params))
    src = os.path.join(HERE, "rs232_console_case.scad")
    with open(src, "w") as fh:
        fh.write(scad.lstrip())
    print("wrote", src)
    outer = (P["pcb_w"] + 2 * P["gap"] + 2 * P["wall"], P["pcb_h"] + P["gap"] + 1.0 + P["wall"] + P["end_wall"],
             P["z_top"] + P["pcb_t"] + P["pin_clr"] + P["bat_t"] + P["base_t"] + P["base_inset"])
    print("outer size: %.1f x %.1f x %.1f mm" % outer)
    for part, name in ((1, "body"), (2, "base")):
        out = os.path.join(HERE, f"{name}.stl")
        r = subprocess.run(["openscad", "-q", "-D", f"part={part}", "-o", out, src], capture_output=True, text=True)
        print(name, "stl:", "ok" if r.returncode == 0 else r.stderr[-600:])
    return 0


if __name__ == "__main__":
    sys.exit(main())
