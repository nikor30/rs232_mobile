#!/usr/bin/env python3
"""Write the OpenSCAD source of the enclosure from the carrier's dimension table
and render STL files + previews with openscad.

    python3 generate_enclosure.py          # writes rs232_console_case.scad, tub.stl, bezel.stl, *.png

Coordinates: carrier PCB top-left corner = origin, X right, Y towards the RJ45
edge, Z up with Z = 0 on the carrier's top surface.  The Waveshare module sits
11 mm above the carrier (stack height of the sockets), its glass top is at
Z = 16.1 and flush with the bezel.
"""
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "carrier"))
import generate as G   # noqa: E402

V = G.V
P = {
    "pcb_w": G.BOARD_W, "pcb_h": G.BOARD_H, "pcb_t": 1.6,
    "gap": 0.5, "wall": 2.5, "side_wall": 4.0, "floor_t": 2.0, "corner_r": 3.0,
    "bat_t": 6.5, "pin_clr": 2.0,
    "z_part": 14.0,                                            # tub / bezel parting line
    "z_glass_top": V["WS_STACK"] + V["WS_PCB_T"] + V["WS_DISP_T"],
    "z_glass_bot": V["WS_STACK"] + V["WS_PCB_T"],
    "ws_x0": G.WS_X0, "ws_y0": G.WS_Y0, "ws_l": V["WS_L"], "ws_w": V["WS_W"],
    "glass_w": V["WS_GLASS"][0], "glass_l": V["WS_GLASS"][1],
    "ch_pitch": G.CH_PITCH, "ch_x0": G.CH_CENTERS[0],
    "rj_w": V["RJ45_W"] + 0.6, "rj_h": V["RJ45_H"] + 0.5,
    "usb_y": G.WS_Y0 + V["WS_W"] - (V["WS_USBC"][0] + V["WS_USBC"][1]) / 2,
    "usb_z": V["WS_STACK"] - 1.6,                               # centre of the USB-C shell (3.2 mm tall, on the module's underside)
    "btn_y1": G.WS_Y0 + V["WS_W"] - sum(V["WS_BTN_X"][1]) / 2,   # BOOT
    "btn_y2": G.WS_Y0 + V["WS_W"] - sum(V["WS_BTN_X"][0]) / 2,   # RST
    "btn_z": V["WS_STACK"] - 1.6,
    "sd_x1": G.WS_X0 + V["WS_SD"][0] - 0.5, "sd_x2": G.WS_X0 + V["WS_SD"][1] + 0.5,
    "sd_z": V["WS_STACK"] - 1.4,
    "sma_y": 10.0, "sma_z": 7.5, "sma_d": 6.5,
}
HOLES_M25 = G.MOUNT_HOLES
HOLES_M2 = [tuple(round(v, 2) for v in h) for h in G.ws_holes_landscape()]
BOSSES = [(-2.5, 87.5), (74.5, 87.5)]   # bezel screws in the side walls, M2 self tapping

SCAD = r"""
// RS232 console server - enclosure for the carrier board + Waveshare ESP32-S3-Touch-LCD-2
// GENERATED by hardware/enclosure/generate_enclosure.py - edit the parameters there or here.
// part = 0: assembly preview, 1: tub (bottom shell), 2: bezel (top plate)
part = 0;
$fn = 48;

__PARAMS__

cav_x1 = -gap;  cav_x2 = pcb_w + gap;       // cavity
cav_y1 = -gap;  cav_y2 = pcb_h + gap;
out_x1 = cav_x1 - side_wall; out_x2 = cav_x2 + side_wall;
out_y1 = cav_y1 - wall;      out_y2 = cav_y2 + wall;
z_pcb_bot = -pcb_t;
z_floor_top = z_pcb_bot - pin_clr - bat_t;
z_floor_bot = z_floor_top - floor_t;
bezel_t = z_glass_top - z_part;

module rbox(x1, y1, x2, y2, z1, z2, r) {
    hull() for (x = [x1 + r, x2 - r], y = [y1 + r, y2 - r])
        translate([x, y, z1]) cylinder(r = r, h = z2 - z1);
}

module standoffs(z1, z2) {
    for (h = holes_m25) translate([h[0], h[1], z1]) cylinder(d = 5.5, h = z2 - z1);
    for (h = holes_m2)  translate([h[0], h[1], z1]) cylinder(d = 5.0, h = z2 - z1);
}

module standoff_holes() {
    for (h = holes_m25) translate([h[0], h[1], z_floor_bot - 1]) {
        cylinder(d = 2.8, h = 50);
        cylinder(d = 5.2, h = 1 + 1.2);                 // counterbore for the screw head
    }
    for (h = holes_m2) translate([h[0], h[1], z_floor_bot - 1]) {
        cylinder(d = 2.3, h = 50);
        cylinder(d = 4.5, h = 1 + 1.2);
    }
}

module tub() {
    difference() {
        union() {
            rbox(out_x1, out_y1, out_x2, out_y2, z_floor_bot, z_part, corner_r);
        }
        // cavity
        translate([cav_x1, cav_y1, z_floor_top]) cube([cav_x2 - cav_x1, cav_y2 - cav_y1, 100]);
        // RJ45 openings in the front wall, open to the top (closed by the bezel)
        for (i = [0:3]) translate([ch_x0 + i * ch_pitch - rj_w / 2, cav_y2 - 1, -0.3])
            cube([rj_w, wall + 2, rj_h + 1]);
        // right wall lowered under the display glass (the glass overhangs the module by 4.6 mm)
        translate([cav_x2 - 0.1, cav_y1 - 1, z_glass_bot - 0.3]) cube([side_wall + 1, ws_y0 + ws_w + 0.6 + 0.3 + 1 - cav_y1, 20]);
        // USB-C well
        translate([cav_x2 - 1, usb_y - 6.5, usb_z - 4]) cube([side_wall + 2, 13, 8]);
        // BOOT / RST pin holes
        for (y = [btn_y1, btn_y2]) translate([cav_x2 - 1, y, btn_z]) rotate([0, 90, 0]) cylinder(d = 2.5, h = side_wall + 2);
        // micro-SD slot in the top wall
        translate([sd_x1, out_y1 - 1, sd_z - 1.4]) cube([sd_x2 - sd_x1, wall + 2, 2.8]);
        // RP-SMA bulkhead for the external antenna, left wall
        translate([out_x1 - 1, sma_y, sma_z]) rotate([0, 90, 0]) cylinder(d = sma_d, h = side_wall + 2);
        standoff_holes();
        // bezel screw pilot holes in the side-wall bosses
        for (b = bosses) translate([b[0], b[1], z_part - 8]) cylinder(d = 1.8, h = 9);
    }
    // carrier standoffs
    difference() {
        standoffs(z_floor_top - 0.1, z_pcb_bot);
        standoff_holes();
    }
    // bezel bosses inside the side walls
    difference() {
        for (b = bosses) translate([b[0], b[1], z_floor_top - 0.1]) cylinder(d = 5.0, h = z_part - z_floor_top + 0.1);
        for (b = bosses) translate([b[0], b[1], z_part - 8]) cylinder(d = 1.8, h = 9);
    }
}

module bezel() {
    gx1 = ws_x0 - 4.6 - 0.3;                        // glass outline + clearance, open to the right edge
    gy1 = ws_y0 + ws_w / 2 - glass_w / 2 - 0.3;
    gy2 = ws_y0 + ws_w / 2 + glass_w / 2 + 0.3;
    difference() {
        union() {
            rbox(out_x1, out_y1, out_x2, out_y2, z_part, z_glass_top, corner_r);
            // alignment lip inside the cavity (left wall, top wall left of the glass, right wall below the glass)
            translate([cav_x1 + 0.15, cav_y1 + 0.15, z_part - 1.5]) cube([1.2, cav_y2 - cav_y1 - 0.3, 1.5]);
            translate([cav_x1 + 0.15, cav_y1 + 0.15, z_part - 1.5]) cube([gx1 - cav_x1 - 1, 1.2, 1.5]);
            translate([cav_x2 - 1.35, gy2 + 1, z_part - 1.5]) cube([1.2, cav_y2 - gy2 - 1.15, 1.5]);
        }
        // display window (the glass fills it, top flush)
        translate([gx1, min(gy1, cav_y1), z_part - 5]) cube([100, gy2 - min(gy1, cav_y1), 20]);
        // screws into the carrier spacers and the side-wall bosses
        for (h = holes_m25) translate([h[0], h[1], z_part - 5]) { cylinder(d = 2.8, h = 20); translate([0, 0, 5 + bezel_t - 1.0]) cylinder(d = 5.0, h = 5); }
        for (b = bosses) translate([b[0], b[1], z_part - 5]) { cylinder(d = 2.3, h = 20); translate([0, 0, 5 + bezel_t - 1.0]) cylinder(d = 4.5, h = 5); }
    }
}

module carrier_preview() {
    color("green", 0.6) translate([0, 0, z_pcb_bot]) cube([pcb_w, pcb_h, pcb_t]);
    for (i = [0:3]) color("silver") translate([ch_x0 + i * ch_pitch - 7.95, pcb_h - 20.3, 0]) cube([15.9, 21.3, 13.5]);
    color("royalblue", 0.7) translate([ws_x0, ws_y0, z_glass_bot - 1.6]) cube([ws_l, ws_w, 1.6]);
    color("black", 0.9) translate([ws_x0 - 4.6, ws_y0 + ws_w / 2 - glass_w / 2, z_glass_bot]) cube([glass_l, glass_w, z_glass_top - z_glass_bot]);
    color("orange", 0.5) translate([6, 20, z_floor_top]) cube([50, 60, bat_t]);
}

if (part == 1) tub();
else if (part == 2) bezel();
else { tub(); translate([0, 0, 25]) bezel(); carrier_preview(); }
"""


def main():
    params = []
    for k, v in P.items():
        params.append(f"{k} = {v};")
    params.append("holes_m25 = " + str([list(h) for h in HOLES_M25]) + ";")
    params.append("holes_m2 = " + str([list(h) for h in HOLES_M2]) + ";")
    params.append("bosses = " + str([list(b) for b in BOSSES]) + ";")
    scad = SCAD.replace("__PARAMS__", "\n".join(params))
    src = os.path.join(HERE, "rs232_console_case.scad")
    with open(src, "w") as fh:
        fh.write(scad.lstrip())
    print("wrote", src)
    outer = (P["pcb_w"] + 2 * P["gap"] + 2 * P["side_wall"], P["pcb_h"] + 2 * P["gap"] + 2 * P["wall"],
             P["z_glass_top"] - (-P["pcb_t"] - P["pin_clr"] - P["bat_t"] - P["floor_t"]))
    print("outer size: %.1f x %.1f x %.1f mm" % outer)
    for part, name in ((1, "tub"), (2, "bezel")):
        out = os.path.join(HERE, f"{name}.stl")
        r = subprocess.run(["openscad", "-q", "-D", f"part={part}", "-o", out, src], capture_output=True, text=True)
        print(name, "stl:", "ok" if r.returncode == 0 else r.stderr[-400:])
    return 0


if __name__ == "__main__":
    sys.exit(main())
