#!/usr/bin/env python3
"""Assembled-board renders of the carrier, both sides.

    python3 render3d.py        # writes kicad/fab/rs232_carrier-3d-*.png (and the .scad next to them)

The generated footprints carry no vendor 3D models, so every part is drawn from its own footprint
data (fab outline, height, pads) with a colour per part type; the Waveshare module is drawn on its
sockets from the VERIFY numbers.  Good enough to see what sits where and how tall it is.
"""
import math
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import generate as G   # noqa: E402

V = G.V
FAB = os.path.join(HERE, "kicad", "fab")
PCB_T = 1.6

COLOURS = {   # footprint name -> colour (OpenSCAD colour names or hex)
    "R_0603": "#2c2c30", "C_0603": "#c8b89a", "C_0805": "#c8b89a", "LED_0603": "#6fcf6f",
    "D_SOD-123": "#1c1c1c", "D_SMA": "#1c1c1c", "L_5x5": "#5a5a5a",
    "SOT-23": "#1a1a1a", "SOT-23-5": "#1a1a1a", "SOT-23-6": "#1a1a1a", "SOIC-16": "#1a1a1a", "SO6_Opto": "#f2f2ec",
    "SIP-4_DCDC": "#101010", "RJ45_Generic": "#202020", "PinSocket_1x14": "#141414", "PinSocket_1x14_B": "#141414",
    "PinHeader_1x7": "#141414", "JST_PH_2_Vertical": "#f4f1e6",
}


def world(x, y, rot, px, py):
    """KiCad footprint-local -> board coordinates (y down), same convention as kigen.courtyard_world."""
    r = math.radians(rot)
    c, s = math.cos(r), math.sin(r)
    return x + px * c + py * s, y - px * s + py * c


def box_world(x, y, rot, b, mirror=False):
    pts = [(b[0], b[1]), (b[2], b[1]), (b[2], b[3]), (b[0], b[3])]
    if mirror:
        pts = [(-px, py) for px, py in pts]
    w = [world(x, y, rot, px, py) for px, py in pts]
    xs = [p[0] for p in w]
    ys = [p[1] for p in w]
    return min(xs), min(ys), max(xs), max(ys)


def scad_box(b, z1, z2, colour):
    # board y (down) -> scad y (up): y' = BOARD_H - y
    x1, y1, x2, y2 = b
    return (f'color("{colour}") translate([{x1:.3f}, {G.BOARD_H - y2:.3f}, {z1:.3f}]) '
            f'cube([{x2 - x1:.3f}, {y2 - y1:.3f}, {z2 - z1:.3f}]);')


def build_scad():
    placed, _ = G.build(write=False)   # placement only, never touch the routed board files
    o = ["// GENERATED by hardware/carrier/render3d.py - assembled carrier board", "$fn = 32;",
         "module pcb() {", "  difference() {",
         f'    color("#1f6b3a") cube([{G.BOARD_W}, {G.BOARD_H}, {PCB_T}]);']
    for p, _, _ in placed:
        fp = G.FPS[p.fp]
        for pad in fp.pads:
            if pad.kind in ("npth", "tht") and pad.drill > 0:
                wx, wy = world(p.x, p.y, p.rot, pad.x, pad.y)
                o.append(f'    translate([{wx:.3f}, {G.BOARD_H - wy:.3f}, -1]) cylinder(d = {pad.drill:.2f}, h = {PCB_T + 2});')
    s = G.BAT_SLOT
    o.append(f'    translate([{s[0]}, {G.BOARD_H - s[3]}, -1]) cube([{s[2] - s[0]}, {s[3] - s[1]}, {PCB_T + 2}]);')
    o += ["  }", "}", "", "module parts() {"]
    for p, _, _ in placed:
        fp = G.FPS[p.fp]
        bottom = p.side == "B"
        zs, ze = (PCB_T, PCB_T) if not bottom else (0, 0)
        # pads (thin copper plates on both sides for through-hole, one side for SMD)
        for pad in fp.pads:
            if pad.kind == "npth":
                continue
            pb = (pad.x - pad.w / 2, pad.y - pad.h / 2, pad.x + pad.w / 2, pad.y + pad.h / 2)
            b = box_world(p.x, p.y, p.rot + pad.rot, pb, mirror=bottom)
            if pad.kind == "tht":
                o.append(scad_box(b, PCB_T, PCB_T + 0.04, "#d8b25a"))
                o.append(scad_box(b, -0.04, 0, "#d8b25a"))
            else:
                o.append(scad_box(b, PCB_T, PCB_T + 0.04, "#d8b25a") if not bottom else scad_box(b, -0.04, 0, "#d8b25a"))
        if p.fp.startswith("MountingHole") or p.fp.startswith("SolderJumper") or fp.height <= 0.1:
            continue
        body = fp.fab or fp.courtyard
        b = box_world(p.x, p.y, p.rot, body, mirror=bottom)
        colour = COLOURS.get(p.fp, "#333333")
        if bottom:
            o.append(scad_box(b, -fp.height, 0, colour))
        else:
            o.append(scad_box(b, PCB_T, PCB_T + fp.height, colour))
        if p.fp == "RJ45_Generic":   # port opening on the front face
            o.append(scad_box((b[0] + 1.5, b[3] - 0.6, b[2] - 1.5, b[3] + 0.01), PCB_T + 2.0, PCB_T + fp.height - 1.5, "#3a3a3a"))
        if p.fp.startswith("PinSocket"):   # header pins of the module above the socket
            for pad in fp.pads:
                wx, wy = world(p.x, p.y, p.rot, pad.x, pad.y)
                o.append(f'color("#d0d0d0") translate([{wx - 0.32:.3f}, {G.BOARD_H - wy - 0.32:.3f}, {PCB_T + fp.height:.2f}]) cube([0.64, 0.64, 2.5]);')
    o += ["}", "", "module waveshare() {"]
    x0, y0, w, l = G.WS_X0, G.WS_Y0, V["WS_W"], V["WS_L"]
    z0 = PCB_T + V["WS_STACK"]
    o.append(scad_box((x0, y0, x0 + w, y0 + l), z0 - 2.5, z0, "#141414"))           # header bodies (both rows)
    o.append(scad_box((x0, y0, x0 + w, y0 + l), z0, z0 + V["WS_PCB_T"], "#1f3b73"))    # module PCB
    gw, gl = V["WS_GLASS"]
    gx1 = x0 + w / 2 - gw / 2
    gy1 = y0 + l / 2 - gl / 2
    zg = z0 + V["WS_PCB_T"]
    o.append(scad_box((x0 + 0.5, y0 + 0.5, x0 + w - 0.5, y0 + l - 0.5), zg, zg + V["WS_DISP_T"] - 1.1, "#2a2a2a"))   # LCD body
    o.append(f'color("#0b0c10") translate([{gx1:.2f}, {G.BOARD_H - gy1 - gl:.2f}, {zg + V["WS_DISP_T"] - 1.1:.2f}]) '
             f'linear_extrude(1.1) offset(r = {V["WS_GLASS_R"]}) offset(delta = -{V["WS_GLASS_R"]}) square([{gw}, {gl}]);')
    ax1, ax2, ay1, ay2 = V["WS_USBC"]   # x1, x2, y1, y2 (module coordinates)
    ub = G.ws_to_carrier(ax1, ay1), G.ws_to_carrier(ax2, ay2)
    o.append(scad_box((min(ub[0][0], ub[1][0]), min(ub[0][1], ub[1][1]), max(ub[0][0], ub[1][0]), max(ub[0][1], ub[1][1])),
                      z0 + V["WS_PCB_T"], z0 + V["WS_PCB_T"] + 3.2, "#b8b8b8"))      # USB-C shell
    o += ["}", "", "module all() { pcb(); parts(); waveshare(); }", "all();"]
    return "\n".join(o) + "\n"


def main():
    os.makedirs(FAB, exist_ok=True)
    src = os.path.join(FAB, "rs232_carrier-3d.scad")
    with open(src, "w") as fh:
        fh.write(build_scad())
    cx, cy, cz = G.BOARD_W / 2, G.BOARD_H / 2, 8
    views = {   # eye x,y,z, centre x,y,z; --viewall fits the distance
        "top": f"{cx - 110},{cy - 180},{cz + 150},{cx},{cy},{cz}",
        "bottom": f"{cx - 110},{cy - 180},{cz - 160},{cx},{cy},{cz}",
        "top-ortho": f"{cx},{cy - 0.01},{cz + 300},{cx},{cy},{cz}",
        "bottom-ortho": f"{cx},{cy - 0.01},{cz - 300},{cx},{cy},{cz}",
    }
    ok = True
    for name, cam in views.items():
        out = os.path.join(FAB, f"rs232_carrier-3d-{name}.png")
        proj = "o" if name.endswith("ortho") else "p"
        cmd = ["xvfb-run", "-a", "openscad", "-q", "--camera=" + cam, "--projection=" + proj, "--viewall", "--imgsize=1600,1600",
               "--colorscheme=Tomorrow", "--preview", "-o", out, src]
        r = subprocess.run(cmd, capture_output=True, text=True)
        ok &= r.returncode == 0
        print(name, "ok" if r.returncode == 0 else r.stderr[-800:])
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
